DROP TABLE IF EXISTS tmp_training_card_title_map;

CREATE TEMP TABLE tmp_training_card_title_map ON COMMIT DROP AS
WITH target_titles AS (
    SELECT title FROM tmp_training_card_seed_batch
    UNION
    SELECT source_title AS title FROM tmp_training_card_relation_seed
    UNION
    SELECT related_title AS title FROM tmp_training_card_relation_seed
)
SELECT DISTINCT ON (t.title)
    t.title,
    t.id
FROM training_cards t
JOIN target_titles tt
  ON tt.title = t.title
ORDER BY t.title, t.id DESC;

INSERT INTO training_card_relations (
    card_id,
    related_card_id,
    display_order,
    created_at,
    updated_at
)
SELECT
    source_map.id,
    related_map.id,
    r.display_order,
    NOW(),
    NOW()
FROM tmp_training_card_relation_seed r
JOIN tmp_training_card_title_map source_map
  ON source_map.title = r.source_title
JOIN tmp_training_card_title_map related_map
  ON related_map.title = r.related_title
ON CONFLICT (card_id, related_card_id) DO NOTHING;

COMMIT;
